#!/usr/bin/env python3
"""Produce a read-only synchronization plan from a Nextcloud media listing.

Input is JSON emitted by list_music.py. No downloads, uploads or deletion.
"""
import argparse
import json
from pathlib import Path

SUPPORTED = {".mp3", ".mp4"}

def plan(data):
    result = []
    for item in data.get("files", []):
        name = item.get("name", "")
        suffix = Path(name).suffix.lower()
        if suffix not in SUPPORTED:
            continue
        size = item.get("size_bytes")
        result.append({
            "name": name,
            "source_format": suffix[1:],
            "size_bytes": size,
            "etag": item.get("etag"),
            "action": "inspect_audio_stream_then_transcode" if suffix == ".mp4" else "inspect_then_import",
            "status": "pending",
        })
    return {"count": len(result), "items": result, "dry_run": True}

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("listing", type=Path, help="JSON file generated by list_music.py")
    args = parser.parse_args()
    data = json.loads(args.listing.read_text(encoding="utf-8"))
    print(json.dumps(plan(data), indent=2, ensure_ascii=False))

if __name__ == "__main__":
    main()
